namespace Mutitasking
{
    public class DoHomework
    {
        public DoHomework() { }

        public void StartHomework()
        {
            Console.WriteLine("Starting my homework...\n");
        }

        public void QuickBreak()
        {
            Console.WriteLine("Taking a quick break from my homework...\n");
        }

        public void TurnInHomework()
        {
            Console.WriteLine("Now I need to turn in my assignment...\n");
        }

        public void Done()
        {
            Console.WriteLine("Done with my homework!...\n");
        }
    }
}
